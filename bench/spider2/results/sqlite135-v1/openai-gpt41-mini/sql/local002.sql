WITH daily_sales AS (
    SELECT DATE(orders.order_purchase_timestamp) AS sale_date, COUNT(order_items.order_id) AS toy_sales
    FROM orders
    JOIN order_items ON orders.order_id = order_items.order_id
    WHERE orders.order_purchase_timestamp BETWEEN '2017-01-01' AND '2018-08-29'
    GROUP BY sale_date
),
indexed_sales AS (
    SELECT sale_date, toy_sales,
           JULIANDAY(sale_date) - JULIANDAY('2017-01-01') AS day_index
    FROM daily_sales
),
coefficients AS (
    SELECT 
        COUNT(*) AS n,
        AVG(day_index) AS avg_x,
        AVG(toy_sales) AS avg_y,
        AVG(day_index * toy_sales) AS avg_xy,
        AVG(day_index * day_index) AS avg_xx
    FROM indexed_sales
),
regression AS (
    SELECT 
        (avg_xy - avg_x * avg_y) / (avg_xx - avg_x * avg_x) AS slope,
        avg_y - ((avg_xy - avg_x * avg_y) / (avg_xx - avg_x * avg_x)) * avg_x AS intercept
    FROM coefficients
),
