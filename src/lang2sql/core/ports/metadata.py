"""Metadata operations shared by local and Oracle-backed tool runtimes."""

from typing import Protocol


class MetadataStorePort(Protocol):
    def kv_get(self, scope: str, key: str) -> str | None: ...
    def kv_set(self, scope: str, key: str, value: str) -> None: ...
    def kv_compare_replace(
        self, scope: str, key: str, expected: str | None, value: str
    ) -> bool: ...
    def kv_delete(self, scope: str, key: str) -> bool: ...
    def kv_list_prefix(self, scope: str, prefix: str) -> list[tuple[str, str]]: ...
    def kv_delete_prefix(self, scope: str, prefix: str) -> int: ...
    def close(self) -> None: ...
